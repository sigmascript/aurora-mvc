"""General behavior checks for explicit, create-only schema generation."""

import sqlite3

import pytest

from aurora.aurorasql import Model, column, connect, create_table, create_table_sql, create_tables


class Entry(Model):
    id = column(int, primary_key=True)
    title = column(str, length=60, unique=True)
    notes = column(str, nullable=True)
    active = column(bool, default=True)


def test_sqlite_schema_and_full_crud_workflow():
    with connect("sqlite:///:memory:") as db:
        create_table(db, Entry)
        entries = Entry.using(db)
        with db.transaction():
            first = entries.create(title="Aurora")
            assert first.id == 1
            assert first.active is True
            assert entries.first(where={"id": first.id}).title == "Aurora"
            assert entries.update(values={"title": "AuroraSQL"}, where={"id": first.id}) == 1
        assert entries.first(where={"title": "AuroraSQL"}).id == 1
        with pytest.raises(sqlite3.IntegrityError):
            entries.create(title="AuroraSQL")
        with pytest.raises(sqlite3.OperationalError):
            create_table(db, Entry)  # Never silently accept an existing table
        assert entries.delete(where={"id": first.id}) == 1


def test_dialect_ddl_and_rejected_unsupported_schema():
    sqlite_sql = create_table_sql(Entry, "sqlite")
    mysql_sql = create_table_sql(Entry, "mysql")
    pg_sql = create_table_sql(Entry, "postgresql")
    assert '"id" INTEGER PRIMARY KEY' in sqlite_sql
    assert '`id` BIGINT AUTO_INCREMENT PRIMARY KEY' in mysql_sql
    assert '"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' in pg_sql
    assert '"title" VARCHAR(60) NOT NULL UNIQUE' in pg_sql
    assert "DEFAULT" not in sqlite_sql  # Python defaults remain application-side
    with pytest.raises(ValueError, match="dialect"):
        create_table_sql(Entry, "oracle")

    class Composite(Model):
        left = column(int, primary_key=True)
        right = column(int, primary_key=True)

    with pytest.raises(ValueError, match="Composite"):
        create_table_sql(Composite, "sqlite")

    class Tag(Model):
        value = column(str, unique=True)

    with pytest.raises(ValueError, match="length"):
        create_table_sql(Tag, "mysql")


def test_create_tables_explicit_multiple_models():
    class Label(Model):
        id = column(int, primary_key=True)
        name = column(str)

    with connect("sqlite:///:memory:") as db:
        create_tables(db, Entry, Label)
        assert Entry.using(db).create(title="one").id == 1
        assert Label.using(db).create(name="two").id == 1
        with pytest.raises(ValueError, match="At least one"):
            create_tables(db)
