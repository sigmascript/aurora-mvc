"""Opt-in cross-backend JOIN checks on explicitly disposable databases."""

import os
from uuid import uuid4

import pytest

from aurora.aurorasql import Model, column, connect, create_table


@pytest.mark.parametrize("dialect,environment", [
    ("mysql", "AURORASQL_TEST_MYSQL_URL"),
    ("postgresql", "AURORASQL_TEST_POSTGRESQL_URL"),
])
def test_live_chained_joins_projection_filters_and_legacy_shape(dialect, environment):
    if os.getenv("AURORASQL_TEST_ALLOW_DDL") != "YES_DISPOSABLE_DB":
        pytest.skip("Requires explicit disposable-database DDL opt-in")
    url = os.getenv(environment)
    if not url:
        pytest.skip(f"{environment} not configured")

    suffix = uuid4().hex[:12]
    authors_table = "join_authors_" + suffix
    books_table = "join_books_" + suffix
    ratings_table = "join_ratings_" + suffix

    Author = type("Author", (Model,), {
        "__table__": authors_table,
        "id": column(int, primary_key=True),
        "name": column(str, length=80),
    })
    Book = type("Book", (Model,), {
        "__table__": books_table,
        "id": column(int, primary_key=True),
        "author_id": column(int),
        "title": column(str, length=80),
    })
    Rating = type("Rating", (Model,), {
        "__table__": ratings_table,
        "id": column(int, primary_key=True),
        "book_id": column(int),
        "score": column(int),
    })

    with connect(url) as db:
        assert db.dialect == dialect
        created = []
        try:
            for model in (Author, Book, Rating):
                create_table(db, model)
                created.append(model.__table_name__)

            with db.transaction():
                Author.using(db).create(id=1, name="Mira")
                Author.using(db).create(id=2, name="Noor")
                Book.using(db).create(id=10, author_id=1, title="First")
                Book.using(db).create(id=11, author_id=2, title="Second")
                Rating.using(db).create(id=100, book_id=10, score=4)
                Rating.using(db).create(id=101, book_id=11, score=5)

            two = Book.using(db).read().join(Author, on=("author_id", "id"))
            legacy_rows = two.order_by("id").all()
            assert legacy_rows == [
                {
                    "left__id": 10, "left__author_id": 1,
                    "left__title": "First", "right__id": 1,
                    "right__name": "Mira",
                },
                {
                    "left__id": 11, "left__author_id": 2,
                    "left__title": "Second", "right__id": 2,
                    "right__name": "Noor",
                },
            ]

            chained = (
                Book.using(db).read()
                .join(Author, on=("author_id", "id"))
                .join(Rating, on=(f"{books_table}.id", "book_id"))
                .select(
                    f"{books_table}.title",
                    f"{authors_table}.name",
                    f"{ratings_table}.score",
                )
            )
            assert chained.order_by(f"{ratings_table}.score", descending=True).all() == [
                {"left__title": "Second", "right1__name": "Noor", "right2__score": 5},
                {"left__title": "First", "right1__name": "Mira", "right2__score": 4},
            ]
            assert chained.count() == 2
            paged = chained.order_by(f"{ratings_table}.score", descending=True)
            assert paged.limit(1).offset(1).all() == [
                {"left__title": "First", "right1__name": "Mira", "right2__score": 4}
            ]

            filtered = chained.where_joined({
                f"{authors_table}.name": "Mira",
                f"{ratings_table}.score--gt": 3,
            })
            assert filtered.count() == 1
            assert filtered.first() == {
                "left__title": "First", "right1__name": "Mira", "right2__score": 4
            }
            assert chained.where_joined({
                f"{authors_table}.name": "Mira' OR 1=1 --"
            }).count() == 0

            with pytest.raises(ValueError):
                chained.select(f"{authors_table}.unknown")
            with pytest.raises(ValueError):
                chained.order_by(f"{ratings_table}.score;DROP")
            with pytest.raises(TypeError, match="Unknown column"):
                chained.where_joined({f"{authors_table}.unknown": "Mira"})
        finally:
            # Only drop tables generated by this test. On failure, inspect the
            # traceback before rerunning; cleanup may itself raise an error.
            for table in reversed(created):
                quoted = f"`{table}`" if dialect == "mysql" else f'"{table}"'
                db.execute_write(f"DROP TABLE {quoted}")
