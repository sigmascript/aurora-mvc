_HISTORY_DDL = {
    "mysql": (
        "CREATE TABLE __migrations__ (id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY, "
        "title TEXT NOT NULL, snapshot VARCHAR(80) NOT NULL, "
        "date VARCHAR(40) NOT NULL, warnings TEXT NULL)"
    ),
    "postgresql": (
        "CREATE TABLE __migrations__ (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
        "title TEXT NOT NULL, snapshot TEXT NOT NULL, "
        "date TEXT NOT NULL, warnings TEXT NULL)"
    ),
}


def _write_snapshot(connection, root, alias, models, title):
    folder = _directory(root, alias)
    contents = {
        "database": alias,
        "engine": connection.dialect,
        "title": title,
        "models": schema_snapshot(*models, dialect=connection.dialect, allow_v2=True)["tables"],
        "physical_schema": _physical(connection),
    }
    observed_tables = {item["table"] for item in contents["physical_schema"]}
    expected_tables = {model.__table_name__ for model in models}

    if observed_tables != expected_tables:
        raise RuntimeError("Observed server tables differ from validated models")
    folder.mkdir(parents=True, exist_ok=True)
    _directory(root, alias)  # Recheck immediately before writing.

    payload = json.dumps(contents, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    for attempt in range(1000):
        filename = timestamp + (f"-{attempt}" if attempt else "") + ".json"
        path = folder / filename
        try:
            with path.open("x", encoding="utf-8", newline="\n") as output:
                output.write(payload)
            return path
        except FileExistsError:
            continue
    raise RuntimeError("No available server snapshot filename")


def _initialize_locked(connection, models, root, alias, title):
    """Require caller-held PostgreSQL transaction or MySQL migration lock."""
    from .cli_init import _preflight, _unsafe_warnings
    from .schema_inspection import verify_server_declared_schema

    report = _preflight(connection, models, alias)
    if report["status"] != "EMPTY" or _unsafe_warnings(report):
        raise RuntimeError("Server database is not empty; initialization refused")
    # The schema and folder must be independently verified before the first DDL.
    _directory(root, alias)
    for model in models:
        if model.__table_name__ in (
            TABLE,
            LEGACY_TABLE,
            "__backups__",
        ) or model.__table_name__.startswith("aurorasql_"):
            raise ValueError("Model table name is reserved for migration history")
    # MySQL DDL may commit even if a later statement or evidence write fails.
    # Keep the original exception and all available evidence for reconciliation.
    try:
        connection.execute_write(_HISTORY_DDL[connection.dialect])

        for model in models:
            connection.execute_write(create_table_sql(model, connection.dialect, models=models))

        verify_server_declared_schema(
            connection, models, history_tables={TABLE}, allow_extended=True
        )
        path = _write_snapshot(connection, root, alias, models, title)
        record = {
            "title": title,
            "snapshot": path.name,
            "date": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "warnings": None,
        }
        connection.execute_write(
            f"INSERT INTO {TABLE} (title,snapshot,date,warnings) "
            "VALUES (:title,:snapshot,:date,:warnings)",
            record,
        )
        # A PostgreSQL rollback can leave an orphan snapshot file; retain it
        # as evidence rather than deleting it after an uncertain commit.
        rows, _ = read_history(connection, root, alias)
        if (
            len(rows) != 1
            or rows[0]["id"] != 1
            or any(rows[0][key] != value for key, value in record.items())
        ):
            raise RuntimeError("Server initialization history completion was not verified")
    except Exception as exc:
        if connection.dialect == "mysql":
            raise RuntimeError(
                "MySQL initialization outcome uncertain after DDL began; "
                "inspect physical schema, migration history, and snapshots "
                "before any retry"
            ) from exc
        raise

    return path


def execute_server_forward_init(
    connection,
    models,
    root,
    alias,
    *,
    approval,
    expected_approval,
    expected_identity,
    parsed,
    title="Initial migration",
):
    """Execute a fresh, explicitly approved schema; fail closed on uncertainty.

    MySQL DDL is non-transactional. A failed initialization may leave physical
    tables; the next attempt refuses nonempty state. PostgreSQL uses one DDL
    transaction and a transaction-scoped advisory lock.
    """
    from .cli_init import (
        _mysql_approval_digest,
        _mysql_database_identity,
        _postgres_approval_digest,
        _postgres_database_identity,
    )
    from .schema import validate_init_models

    dialect = connection.dialect
    if dialect not in _HISTORY_DDL:
        raise ValueError("Fresh server initialization requires MySQL or PostgreSQL")
    if not isinstance(title, str) or not title.strip():
        raise ValueError("Initial migration title is required")
    if (
        not isinstance(expected_approval, str)
        or len(expected_approval) != 64
        or approval != expected_approval
    ):
        raise PermissionError("Exact reviewed schema approval is required")
    if expected_identity is None or parsed is None:
        raise ValueError("Verified server database identity is required")
    ordered = validate_init_models(models, dialect=dialect, allow_extended=True)
    if list(ordered) != list(models):
        raise ValueError("Models must follow validated dependency order")
    if dialect == "mysql":
        identity_fn = _mysql_database_identity
        digest_fn = _mysql_approval_digest
    else:
        identity_fn = _postgres_database_identity
        digest_fn = _postgres_approval_digest
    connection._ensure_open()
    if connection._transaction_active:
        raise RuntimeError("Cannot nest migration execution inside a transaction")
    # Check the snapshot destination before any DDL.
    _directory(root, alias)
    if dialect == "postgresql":
        with connection.transaction():
            row = connection.fetch_first(
                "SELECT pg_try_advisory_xact_lock(:key) AS acquired", {"key": _PG_LOCK_KEY}
            )
            if not row or row["acquired"] is not True:
                raise RuntimeError("PostgreSQL migration lock unavailable")
            identity = identity_fn(connection, parsed)
            if (
                identity != expected_identity
                or digest_fn(ordered, alias, identity) != expected_approval
            ):
                raise RuntimeError("Server identity or reviewed schema changed")
            snapshot_path = _initialize_locked(connection, ordered, root, alias, title)
    else:
        with migration_lock(connection):
            identity = identity_fn(connection, parsed)
            if (
                identity != expected_identity
                or digest_fn(ordered, alias, identity) != expected_approval
            ):
                raise RuntimeError("Server identity or reviewed schema changed")
            snapshot_path = _initialize_locked(connection, ordered, root, alias, title)
    return snapshot_path


def verify_interrupted_addition(connection, root, database, models, target):
    """Prove precisely one nullable plain column was added since latest history."""
    if connection.dialect != "mysql" or history_table(connection) != TABLE:
        raise RuntimeError("Recovery requires MySQL five-column migration history")
    _verify_table(connection, TABLE)
    directory = _directory(root, database)
    if not directory.is_dir() or directory.is_symlink():
        raise RuntimeError("Recorded migration snapshot directory is unavailable")
    rows = connection.fetch_all(
        "SELECT id,title,snapshot,date,warnings FROM __migrations__ ORDER BY id"
    )
    if not rows or [row["id"] for row in rows] != list(range(1, len(rows) + 1)):
        raise RuntimeError("Migration history is incomplete or out of sequence")
    # Temporarily verify predecessor against a known snapshot rather than
    # calling read_history, which correctly refuses current physical drift.
    import json

    from .migration_history import _FILE

    seen = set()
    predecessor = None
    for row in rows:
        name = row["snapshot"]
        if (
            not isinstance(name, str)
            or not _FILE.fullmatch(name)
            or name in seen
            or not row["title"]
            or not row["date"]
        ):
            raise RuntimeError("Migration history has invalid evidence")
        seen.add(name)
        path = directory / name
        if path.is_symlink() or not path.is_file():
            raise RuntimeError("Migration snapshot evidence is missing")
        try:
            entry = json.loads(path.read_text(encoding="utf-8"))
        except (ValueError, OSError) as exc:
            raise RuntimeError("Migration snapshot evidence cannot be read") from exc
        if (
            not isinstance(entry, dict)
            or entry.get("database") != database
            or entry.get("engine") != "mysql"
            or entry.get("title") != row["title"]
            or not isinstance(entry.get("models"), list)
            or not isinstance(entry.get("physical_schema"), list)
        ):
            raise RuntimeError("Migration snapshot evidence is inconsistent")
        predecessor = entry
    # Preserve and refuse unrecorded files (including partial prior recovery).
    if {p.name for p in directory.iterdir()} != seen:
        raise RuntimeError("Unrecorded migration snapshot evidence requires manual review")
    if len(rows) != 1:
        raise RuntimeError("Automatic history-only repair is limited to the first successor")

    table_name, separator, column_name = target.partition(".")
    if not separator or not table_name or not column_name:
        raise ValueError("Recovery target must be TABLE.COLUMN")
    declarations = schema_snapshot(*models, dialect="mysql", allow_v2=True)["tables"]
    previous_models = predecessor["models"]
    if len(declarations) != len(previous_models) or {m["name"] for m in declarations} != {
        m["name"] for m in previous_models
    }:
        raise RuntimeError("Model table identity differs from predecessor")
    old_by_name = {m["name"]: m for m in previous_models}
    for current in declarations:
        old = old_by_name[current["name"]]
        if current["name"] == table_name:
            old_columns = old["columns"]
            new_columns = current["columns"]
            if (
                len(new_columns) != len(old_columns) + 1
                or new_columns[:-1] != old_columns
                or new_columns[-1]["name"] != column_name
            ):
                raise RuntimeError("Model change is not one appended column")
            added = new_columns[-1]
            if (
                not added["nullable"]
                or added["primary_key"]
                or added["unique"]
                or added["references"] is not None
                or added["server_default"] is not None
                or added["python_default"] != {"kind": "literal", "value": None}
            ):
                raise RuntimeError("Recovery requires a plain nullable new column")
        elif current != old:
            raise RuntimeError("Unrelated model declarations differ from predecessor")

    # Native catalog verification includes triggers, indexes, keys, defaults,
    # exact types, and the independently validated internal backup catalog.
    verify_server_declared_schema(connection, models, history_tables={TABLE})
    before = predecessor["physical_schema"]
    now = _physical(connection)
    if len(now) != len(before) or [x["table"] for x in now] != [x["table"] for x in before]:
        raise RuntimeError("Physical table identities differ from predecessor")
    for current, old in zip(now, before):
        if current["table"] != table_name:
            if current != old:
                raise RuntimeError("Unrelated physical schema differs from predecessor")
            continue
        expected = {**old, "columns": old["columns"] + current["columns"][-1:]}
        if (
            len(current["columns"]) != len(old["columns"]) + 1
            or [item[0] for item in current["columns"][:-1]] != [item[0] for item in old["columns"]]
            or current["columns"][-1][0] != column_name
            or current != expected
        ):
            raise RuntimeError("Physical drift is not exactly the declared column")
    return rows


def _verify_backups(connection, root, database, url):
    """Read-only independent manifest/catalog integrity before history recovery."""
    from .backup_catalog import destination_fingerprint, inspect_server_catalog, list_artifacts

    fingerprint = destination_fingerprint(url)
    reports = list_artifacts(root, database, fingerprint)
    reports = inspect_server_catalog(connection, root, database, fingerprint, reports)
    if any(report["status"] != "ARTIFACT_VERIFIED" for report in reports):
        raise RuntimeError("Existing backup evidence is inconsistent")


def reconcile_interrupted_addition(
    connection, root, database, models, target, title, *, expected_identity, parsed, configured_url
):
    """Perform history-only completion under the established migration lock."""
    from .connections import _mysql_database_identity

    if project_is_production(root):
        raise PermissionError("Production recovery is disabled")
    if connection._transaction_active or getattr(connection, "_migration_lock_active", False):
        raise RuntimeError("Recovery cannot nest transactions or locks")
    if not isinstance(title, str) or not title.strip():
        raise ValueError("A recovery migration title is required")
    with migration_lock(connection):
        if _mysql_database_identity(connection, parsed) != expected_identity:
            raise RuntimeError("MySQL database identity changed before recovery")
        rows = verify_interrupted_addition(connection, root, database, models, target)
        _verify_backups(connection, root, database, configured_url)
        snapshot = _write_snapshot(connection, root, database, models, title)
        record = {
            "id": len(rows) + 1,
            "title": title,
            "snapshot": snapshot.name,
            "date": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "warnings": None,
        }
        try:
            connection.execute_write(
                "INSERT INTO __migrations__ (id,title,snapshot,date,warnings) "
                "VALUES (:id,:title,:snapshot,:date,:warnings)",
                record,
            )
            verified, _ = read_history(connection, root, database)
            if len(verified) != record["id"] or any(
                verified[-1][key] != value for key, value in record.items()
            ):
                raise RuntimeError("Reconciled migration history could not be verified")
        except Exception as exc:
            raise RuntimeError(
                "History-only recovery outcome uncertain; preserve the new snapshot "
                "and inspect SQL history before any further action"
            ) from exc
        return snapshot


# SQLite forward-history ownership (R4.15).
def sqlite_initialize(raw, root, db_file, models, title):
    """Create a complete fresh schema and its first history record atomically."""
    from .constraints import matches_models_with_indexes
    from .migration_history import (
        _SQLITE_OLD as _OLD,
    )
    from .migration_history import (
        SQLITE_BACKUP_TABLE as BACKUP_TABLE,
    )
    from .migration_history import (
        SQLITE_LEGACY_TABLE as LEGACY_TABLE,
    )
    from .migration_history import (
        SQLITE_TABLE as TABLE,
    )
    from .migration_history import (
        _sqlite_tables as _tables,
    )
    from .migration_history import (
        sqlite_new_record as _new_record,
    )
    from .schema import create_table_sql

    DDL = (
        'CREATE TABLE "__migrations__" ('
        '"id" INTEGER PRIMARY KEY, "title" TEXT NOT NULL, '
        '"snapshot" TEXT NOT NULL, "date" TEXT NOT NULL, "warnings" TEXT)'
    )
    if any(
        m.__table_name__ in (TABLE, LEGACY_TABLE, BACKUP_TABLE) or m.__table_name__ in _OLD
        for m in models
    ):
        raise ValueError("A model table name is reserved for Aurora migration history")
    if raw.in_transaction or _tables(raw):
        raise RuntimeError("Initialization requires an empty database")
    raw.execute("PRAGMA foreign_keys=ON")
    if raw.execute("PRAGMA foreign_keys").fetchone()[0] != 1:
        raise RuntimeError("SQLite foreign keys must be enabled")
    path = None
    try:
        raw.execute("BEGIN IMMEDIATE")
        if _tables(raw):
            raise RuntimeError("Database changed before initialization")
        raw.execute(DDL)
        for model in models:
            raw.execute(create_table_sql(model, "sqlite", models=models))
        matches_models_with_indexes(raw, models)
        if raw.execute("PRAGMA foreign_key_check").fetchall():
            raise ValueError("Rename would leave invalid foreign-key references")
        path = _new_record(raw, root, db_file, models, title)
        raw.commit()
    except BaseException:
        raw.rollback()
        if path is not None:
            path.unlink(missing_ok=True)
        raise
    return path
