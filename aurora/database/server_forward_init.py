"""Guarded five-column initialization for fresh MySQL/PostgreSQL databases."""

import json
from datetime import datetime, timezone

from .coordination import _PG_LOCK_KEY, migration_lock
from .schema import create_table_sql
from .server_forward_history import _directory, _physical, read_history
from .snapshots import schema_snapshot


_HISTORY_DDL = {
    "mysql": ("CREATE TABLE migrations (id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY, "
              "title TEXT NOT NULL, snapshot VARCHAR(80) NOT NULL, "
              "date VARCHAR(40) NOT NULL, warnings TEXT NULL)"),
    "postgresql": ("CREATE TABLE migrations (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                   "title TEXT NOT NULL, snapshot TEXT NOT NULL, "
                   "date TEXT NOT NULL, warnings TEXT NULL)"),
}


def _write_snapshot(connection, root, alias, models, title):
    folder = _directory(root, alias)
    contents = {
        "database": alias,
        "engine": connection.dialect,
        "title": title,
        "models": schema_snapshot(*models, dialect=connection.dialect)["tables"],
        "physical_schema": _physical(connection),
    }
    observed_tables = {item["table"] for item in contents["physical_schema"]}
    expected_tables = {model.__table_name__ for model in models}

    if observed_tables != expected_tables:
        raise RuntimeError("Observed server tables differ from validated models")
    folder.mkdir(parents=True, exist_ok=True)
    _directory(root, alias)  # Recheck immediately before writing.

    payload = json.dumps(contents, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    for attempt in range(1000):
        filename = timestamp + (f"-{attempt}" if attempt else "") + ".json"
        path = folder / filename
        try:
            with path.open("x", encoding="utf-8", newline="\n") as output:
                output.write(payload)
            return path
        except FileExistsError:
            continue
    raise RuntimeError("No available server snapshot filename")


def _initialize_locked(connection, models, root, alias, title):
    """Require caller-held PostgreSQL transaction or MySQL migration lock."""
    from .cli_init import _preflight, _unsafe_warnings
    from .server_initial_verification import verify_server_declared_schema

    report = _preflight(connection, models, alias)
    if report["status"] != "EMPTY" or _unsafe_warnings(report):
        raise RuntimeError("Server database is not empty; initialization refused")
    # The schema and folder must be independently verified before the first DDL.
    _directory(root, alias)
    for model in models:
        if (model.__table_name__ == "migrations"
                or model.__table_name__.startswith("aurorasql_")):
            raise ValueError("Model table name is reserved for migration history")
    # MySQL DDL may commit even if a later statement or evidence write fails.
    # Keep the original exception and all available evidence for reconciliation.
    try:
        connection.execute_write(_HISTORY_DDL[connection.dialect])

        for model in models:
            connection.execute_write(create_table_sql(model, connection.dialect))

        verify_server_declared_schema(connection, models, history_tables={"migrations"})
        path = _write_snapshot(connection, root, alias, models, title)
        record = {
            "title": title,
            "snapshot": path.name,
            "date": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "warnings": None,
        }
        connection.execute_write(
            "INSERT INTO migrations (title,snapshot,date,warnings) "
            "VALUES (:title,:snapshot,:date,:warnings)",
            record,
        )
        # A PostgreSQL rollback can leave an orphan snapshot file; retain it
        # as evidence rather than deleting it after an uncertain commit.
        rows, _ = read_history(connection, root, alias)
        if (len(rows) != 1 or rows[0]["id"] != 1
                or any(rows[0][key] != value for key, value in record.items())):
            raise RuntimeError("Server initialization history completion was not verified")
    except Exception as exc:
        if connection.dialect == "mysql":
            raise RuntimeError(
                "MySQL initialization outcome uncertain after DDL began; "
                "inspect physical schema, migration history, and snapshots "
                "before any retry"
            ) from exc
        raise

    return path


def execute_server_forward_init(connection, models, root, alias, *, approval,
                                expected_approval, expected_identity, parsed,
                                title="Initial migration"):
    """Execute a fresh, explicitly approved schema; fail closed on uncertainty.

    MySQL DDL is non-transactional. A failed initialization may leave physical
    tables; the next attempt refuses nonempty state. PostgreSQL uses one DDL
    transaction and a transaction-scoped advisory lock.
    """
    from .cli_init import (_mysql_approval_digest, _mysql_database_identity,
                           _postgres_approval_digest, _postgres_database_identity)
    from .init_validation import validate_init_models

    dialect = connection.dialect
    if dialect not in _HISTORY_DDL:
        raise ValueError("Fresh server initialization requires MySQL or PostgreSQL")
    if not isinstance(title, str) or not title.strip():
        raise ValueError("Initial migration title is required")
    if (not isinstance(expected_approval, str)
            or len(expected_approval) != 64
            or approval != expected_approval):
        raise PermissionError("Exact reviewed schema approval is required")
    if expected_identity is None or parsed is None:
        raise ValueError("Verified server database identity is required")
    ordered = validate_init_models(models, dialect=dialect)
    if list(ordered) != list(models):
        raise ValueError("Models must follow validated dependency order")
    if dialect == "mysql":
        identity_fn = _mysql_database_identity
        digest_fn = _mysql_approval_digest
    else:
        identity_fn = _postgres_database_identity
        digest_fn = _postgres_approval_digest
    connection._ensure_open()
    if connection._transaction_active:
        raise RuntimeError("Cannot nest migration execution inside a transaction")
    # Check the snapshot destination before any DDL.
    _directory(root, alias)
    if dialect == "postgresql":
        with connection.transaction():
            row = connection.fetch_first(
                "SELECT pg_try_advisory_xact_lock(:key) AS acquired", {"key": _PG_LOCK_KEY})
            if not row or row["acquired"] is not True:
                raise RuntimeError("PostgreSQL migration lock unavailable")
            identity = identity_fn(connection, parsed)
            if identity != expected_identity or digest_fn(ordered, alias, identity) != expected_approval:
                raise RuntimeError("Server identity or reviewed schema changed")
            snapshot_path = _initialize_locked(connection, ordered, root, alias, title)
    else:
        with migration_lock(connection):
            identity = identity_fn(connection, parsed)
            if identity != expected_identity or digest_fn(ordered, alias, identity) != expected_approval:
                raise RuntimeError("Server identity or reviewed schema changed")
            snapshot_path = _initialize_locked(connection, ordered, root, alias, title)
    return snapshot_path
